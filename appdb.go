// appDB holds CalibreFast's own data: accounts, sessions, favorites, reading
// progress, bookmarks and bookshelves. It is a separate SQLite file under
// -datadir — never Calibre's metadata.db, and never inside the library folder
// (credentials shouldn't travel with a library that may be synced or shared).
var appDB *sql.DB

const appDBFile = "calibrefast.db"

// migrations are applied in order; each runs once, recorded in schema_version.
// Never edit or reorder an applied migration — add a new one at the end.
var migrations = []string{
	// 1: accounts and sessions
	`
	CREATE TABLE users (
		id            INTEGER PRIMARY KEY,
		username      TEXT    NOT NULL UNIQUE COLLATE NOCASE,
		password_hash TEXT,                       -- NULL: OAuth-only account
		is_admin      INTEGER NOT NULL DEFAULT 0,
		disabled      INTEGER NOT NULL DEFAULT 0,
		created_at    INTEGER NOT NULL
	);
	CREATE TABLE identities (
		provider   TEXT    NOT NULL,              -- "github" | "google"
		subject    TEXT    NOT NULL,              -- provider's stable user id
		user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
		email      TEXT    NOT NULL DEFAULT '',
		login      TEXT    NOT NULL DEFAULT '',
		created_at INTEGER NOT NULL,
		PRIMARY KEY (provider, subject)
	);
	CREATE INDEX identities_user ON identities(user_id);
	CREATE TABLE sessions (
		token_hash TEXT    PRIMARY KEY,           -- sha256 of the cookie value
		user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
		created_at INTEGER NOT NULL,
		expires_at INTEGER NOT NULL
	);
	CREATE INDEX sessions_user ON sessions(user_id);
	`,
	// 2: per-user reading data
	`
	CREATE TABLE favorites (
		user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
		book_uuid  TEXT    NOT NULL,
		created_at INTEGER NOT NULL,
		PRIMARY KEY (user_id, book_uuid)
	);
	CREATE TABLE reading_status (
		user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
		book_uuid  TEXT    NOT NULL,
		status     TEXT    NOT NULL CHECK (status IN ('reading', 'finished')),
		source     TEXT    NOT NULL CHECK (source IN ('manual', 'auto')),
		updated_at INTEGER NOT NULL,
		PRIMARY KEY (user_id, book_uuid)
	);
	CREATE TABLE reading_progress (
		user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
		book_uuid  TEXT    NOT NULL,
		format     TEXT    NOT NULL,              -- "epub" | "pdf"
		position   TEXT    NOT NULL,              -- EPUB CFI or PDF page number
		percent    REAL    NOT NULL DEFAULT 0,    -- 0..1
		updated_at INTEGER NOT NULL,              -- client clock, ms (last writer wins)
		PRIMARY KEY (user_id, book_uuid, format)
	);
	CREATE TABLE bookmarks (
		user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
		book_uuid  TEXT    NOT NULL,
		client_id  TEXT    NOT NULL,              -- id generated by the reader, so offline copies merge
		format     TEXT    NOT NULL,
		position   TEXT    NOT NULL,
		label      TEXT    NOT NULL DEFAULT '',
		created_at INTEGER NOT NULL,
		PRIMARY KEY (user_id, client_id)
	);
	CREATE INDEX bookmarks_book ON bookmarks(user_id, book_uuid);
	`,
	// 3: bookshelves (owner_id NULL = global shelf, managed by admins)
	`
	CREATE TABLE shelves (
		id          INTEGER PRIMARY KEY,
		owner_id    INTEGER REFERENCES users(id) ON DELETE CASCADE,
		name        TEXT    NOT NULL,
		description TEXT    NOT NULL DEFAULT '',
		created_at  INTEGER NOT NULL,
		updated_at  INTEGER NOT NULL
	);
	CREATE INDEX shelves_owner ON shelves(owner_id);
	CREATE TABLE shelf_books (
		shelf_id  INTEGER NOT NULL REFERENCES shelves(id) ON DELETE CASCADE,
		book_uuid TEXT    NOT NULL,
		added_at  INTEGER NOT NULL,
		PRIMARY KEY (shelf_id, book_uuid)
	);
	`,
	// 4: one-time sign-in and invite links (links.go)
	`
	CREATE TABLE login_links (
		token_hash   TEXT    PRIMARY KEY,
		kind         TEXT    NOT NULL CHECK (kind IN ('login', 'invite')),
		user_id      INTEGER REFERENCES users(id) ON DELETE CASCADE, -- sign-in links
		invite_admin INTEGER NOT NULL DEFAULT 0,                    -- invites: create as admin
		note         TEXT    NOT NULL DEFAULT '',
		created_by   INTEGER REFERENCES users(id) ON DELETE SET NULL,
		created_at   INTEGER NOT NULL,
		expires_at   INTEGER NOT NULL,
		used_at      INTEGER,
		used_by      INTEGER REFERENCES users(id) ON DELETE SET NULL
	);`,
	// 5: KOReader progress sync (kosync.go)
	`
	CREATE TABLE sync_keys (
		user_id      INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
		key_hash     TEXT    NOT NULL,            -- sha256 of the MD5 KOReader sends as x-auth-key
		created_at   INTEGER NOT NULL,
		last_used_at INTEGER
	);
	CREATE TABLE device_progress (
		user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
		document   TEXT    NOT NULL,              -- KOReader's document id (partial MD5 or file name MD5)
		progress   TEXT    NOT NULL,              -- XPointer or page number, exactly as sent
		percentage REAL    NOT NULL,
		device     TEXT    NOT NULL,
		device_id  TEXT,
		updated_at INTEGER NOT NULL,              -- server clock, ms
		PRIMARY KEY (user_id, document)
	);
	CREATE TABLE book_digests (                  -- KOReader partial MD5 of library files, cached
		book_uuid TEXT    NOT NULL,
		format    TEXT    NOT NULL,
		digest    TEXT    NOT NULL,
		size      INTEGER NOT NULL,               -- file size and mtime (ns) when hashed
		mtime     INTEGER NOT NULL,
		PRIMARY KEY (book_uuid, format)
	);
	CREATE INDEX book_digests_digest ON book_digests(digest);
	`,
}

// openAppDB opens (creating if needed) and migrates the app database.
func openAppDB(dir string) (*sql.DB, error) {
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return nil, fmt.Errorf("create data dir: %w", err)
	}
	path := filepath.Join(dir, appDBFile)
	dsn := "file:" + path + "?_foreign_keys=on&_journal_mode=WAL&_busy_timeout=5000"
	db, err := sql.Open("sqlite3", dsn)
	if err != nil {
		return nil, err
	}
	db.SetMaxOpenConns(1) // one writer; reads are quick
	if err := migrate(db); err != nil {
		db.Close()
		return nil, err
	}
	// The DB holds password hashes and session tokens: owner-only.
	_ = os.Chmod(path, 0o600)
	return db, nil
}

func migrate(db *sql.DB) error {
	if _, err := db.Exec(`CREATE TABLE IF NOT EXISTS schema_version (version INTEGER NOT NULL)`); err != nil {
		return err
	}
	var version int
	if err := db.QueryRow(`SELECT COALESCE(MAX(version), 0) FROM schema_version`).Scan(&version); err != nil {
		return err
	}
	for i := version; i < len(migrations); i++ {
		tx, err := db.Begin()
		if err != nil {
			return err
		}
		if _, err := tx.Exec(migrations[i]); err != nil {
			tx.Rollback()
			return fmt.Errorf("migration %d: %w", i+1, err)
		}
		if _, err := tx.Exec(`INSERT INTO schema_version (version) VALUES (?)`, i+1); err != nil {
			tx.Rollback()
			return err
		}
		if err := tx.Commit(); err != nil {
			return err
		}
		log.Printf("app db: applied migration %d", i+1)
	}
	return nil
}

func nowUnix() int64 { return time.Now().Unix() }
